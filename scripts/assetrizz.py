#!/usr/bin/env python3
"""Search a pinned Assetrizz manifest or import the curated, verified assets.

Usage: python3 scripts/assetrizz.py search MANIFEST QUERY
       python3 scripts/assetrizz.py import [--library DIRECTORY]
Import requires Pillow. --library reads a local checkout; without it only the
curated files are fetched from the pinned GitHub revision.
"""
import base64
import hashlib
import subprocess
import json
from pathlib import Path
import sys
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parent.parent
CONFIG = json.loads((ROOT / 'scripts/assetrizz.json').read_text())
BASE = 'https://raw.githubusercontent.com/mojomast/assetrizz/' + CONFIG['revision'] + '/'


def digest(data):
    return hashlib.sha256(data).hexdigest()


def download(path):
    with urlopen(BASE + path, timeout=30) as response:
        return response.read(32 * 1024 * 1024 + 1)


def manifest(data):
    if digest(data) != CONFIG['manifestSha256']:
        raise ValueError('manifest SHA-256 mismatch')
    return [json.loads(line) for line in data.splitlines() if line]


def main(args):
    if len(args) == 3 and args[0] == 'search':
        rows = manifest(Path(args[1]).read_bytes())
        query = args[2].lower()
        for row in rows:
            if query in json.dumps(row, ensure_ascii=False).lower():
                print(json.dumps(row, ensure_ascii=False))
        return
    if not args or args[0] != 'import' or (len(args) != 1 and (len(args) != 3 or args[1] != '--library')):
        raise ValueError(__doc__)
    from PIL import Image
    import io
    library = Path(args[2]).resolve() if len(args) == 3 else None
    def read(path):
        return (library / path).read_bytes() if library else download(path)
    rows = {r['path']: r for r in manifest(read('assets/manifest.jsonl'))}
    cache = {}
    def verified(asset):
        path = asset['path']
        if not path.startswith('assets/') or '..' in Path(path).parts or not path.endswith('.png'):
            raise ValueError('invalid asset path')
        row = rows[path]
        if row['sha256'] != asset['sha256'] or row['license'] != CONFIG['license']:
            raise ValueError('catalog provenance mismatch: ' + path)
        if path not in cache:
            cache[path] = read(path)
        data = cache[path]
        if digest(data) != asset['sha256'] or not data.startswith(b'\x89PNG\r\n\x1a\n'):
            raise ValueError('PNG hash or signature mismatch: ' + path)
        with Image.open(io.BytesIO(data)) as image:
            if image.format != 'PNG' or image.size != (row['width'], row['height']):
                raise ValueError('PNG dimensions mismatch: ' + path)
            pixels = image.convert('RGBA').resize((64, 64), Image.Resampling.NEAREST)
        return data, pixels

    def collect(assets, strips):
        outputs = []
        for asset in assets:
          data, pixels = verified(asset)
          outputs.append((asset['key'], data, pixels))
        for strip in strips:
          frames = strip['frames']
          if len(frames) != 4:
              raise ValueError('enemy strip must have idle, walk, attack and hurt frames')
          image = Image.new('RGBA', (64 * len(frames), 64))
          for index, frame in enumerate(frames):
              _, pixels = verified(frame)
              effect = frame.get('effect')
              if effect == 'hurt':
                  red, green, blue, alpha = pixels.split()
                  pixels = Image.merge('RGBA', (red.point(lambda v: (v + 255) // 2),
                                                 green.point(lambda v: v // 2),
                                                 blue.point(lambda v: v // 2), alpha))
              elif effect is not None:
                  raise ValueError('unknown frame effect: ' + str(effect))
              image.paste(pixels, (64 * index, 0))
          buffer = io.BytesIO()
          image.save(buffer, format='PNG')
          outputs.append((strip['key'], buffer.getvalue(), image))
        return outputs
    outputs = collect(CONFIG['assets'], CONFIG['enemyStrips'])
    fantasy = collect(CONFIG['fantasy']['assets'], CONFIG['fantasy']['enemyStrips'])
    # UI plates/icons retain their authored dimensions; they are not repeating 64px world tiles.
    ui = [(asset['key'], verified(asset)[0]) for asset in CONFIG.get('ui', [])]
    # Verify every input before touching outputs.
    out = ROOT / 'public/assetrizz'
    out.mkdir(parents=True, exist_ok=True)
    (out / 'provenance.json').write_text(json.dumps(CONFIG, indent=2) + '\n')
    for key, data, _ in outputs:
        (out / (key + '.png')).write_bytes(data)
    for key, data, _ in fantasy:
        (out / ('fantasy-' + key + '.png')).write_bytes(data)
    for key, data in ui:
        (out / (key + '.png')).write_bytes(data)
    def write_painters(filename, export, items):
        lines = ["// Generated by scripts/assetrizz.py; see scripts/assetrizz.json for provenance.",
               "import type { Painter } from '../../sdk/index.ts';", '',
               'function painter(width: number, encoded: string): Painter {',
               '  return { width, height: 64, paint(ctx) {',
               '    const bytes = Uint8ClampedArray.from(atob(encoded), c => c.charCodeAt(0));',
               '    ctx.putImageData(new ImageData(bytes, width, 64), 0, 0);',
                '  } };', '}', '', f'export const {export}: Record<string, Painter> = {{']
        lines += [f"  '{key}': painter({pixels.width}, '{base64.b64encode(pixels.tobytes()).decode('ascii')}'),"
                  for key, _, pixels in items]
        lines += ['};', '']
        (ROOT / 'packages/std/plugins/theme-assetrizz' / filename).write_text('\n'.join(lines))
    write_painters('generated.ts', 'assetrizzTextures', outputs)
    write_painters('fantasy-generated.ts', 'fantasyTextures', fantasy)
    # Keep pixel data out of JavaScript: move it into content-hashed packs under public/packs/.
    subprocess.run(['node', str(ROOT / 'scripts' / 'pack-painters.mjs'), 'packages/std/plugins/theme-assetrizz/generated.ts',
                    'packages/std/plugins/theme-assetrizz/fantasy-generated.ts'], check=True, cwd=ROOT)
    print('Imported', len(outputs) + len(fantasy), 'verified Assetrizz textures and', len(ui), 'original-size UI images')


if __name__ == '__main__':
    try:
        main(sys.argv[1:])
    except (OSError, ValueError, KeyError) as exc:
        print('assetrizz:', exc, file=sys.stderr)
        sys.exit(1)
