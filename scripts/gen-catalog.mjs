#!/usr/bin/env node
// Generates src/app/catalog.generated.ts from every plugin folder's manifest.json.
// Usage: node scripts/gen-catalog.mjs [--check]
//   --check  exit 1 when the committed file is stale (used by `npm run check`).
//
// A plugin folder is any directory under a plugin root that contains manifest.json. Code plugins have index.ts and
// get a lazy `load: () => import(...)` entry; data-only packs have content.json and get a `content` entry. The
// manifest stays a static JSON import, so the host still validates the whole graph before any plugin code loads.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { relative, resolve, join } from 'node:path';
import { assertNodeVersion } from './check-node.mjs';

assertNodeVersion();
const root = resolve(import.meta.dirname, '..');
export const OUT = 'src/app/catalog.generated.ts';

/** Plugin roots, relative to the repo. Each child folder with a manifest.json is one plugin. */
export function pluginRoots() {
  const roots = ['packages/std/plugins'];
  const games = resolve(root, 'games');
  if (existsSync(games)) {
    for (const g of readdirSync(games, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
      if (existsSync(join(games, g, 'plugins'))) roots.push(`games/${g}/plugins`);
    }
  }
  return roots;
}

export function discoverPlugins() {
  const found = [];
  const ids = new Map();
  for (const r of pluginRoots()) {
    const abs = resolve(root, r);
    if (!existsSync(abs)) continue;
    for (const name of readdirSync(abs, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
      const dir = `${r}/${name}`;
      const manifestPath = resolve(root, dir, 'manifest.json');
      if (!existsSync(manifestPath)) continue;
      let manifest;
      try { manifest = JSON.parse(readFileSync(manifestPath, 'utf8')); } catch (e) { throw new Error(`${dir}/manifest.json: ${e.message}`); }
      const id = manifest?.id;
      if (typeof id !== 'string') throw new Error(`${dir}/manifest.json: missing string "id"`);
      if (ids.has(id)) throw new Error(`duplicate plugin id "${id}" in ${ids.get(id)} and ${dir}`);
      ids.set(id, dir);
      const code = existsSync(resolve(root, dir, 'index.ts'));
      const content = existsSync(resolve(root, dir, 'content.json'));
      if (!code && !content) throw new Error(`${dir}: has manifest.json but neither index.ts nor content.json`);
      if (code && content) throw new Error(`${dir}: has both index.ts and content.json; a plugin is either code or a data pack`);
      found.push({ id, dir, code });
    }
  }
  return found;
}

export function renderCatalog(plugins) {
  const from = resolve(root, 'src/app');
  const rel = (p) => { const r = relative(from, resolve(root, p)); return r.startsWith('.') ? r : `./${r}`; };
  const ident = (i) => `p${i}`;
  const lines = [
    '// GENERATED by scripts/gen-catalog.mjs from every plugin folder\'s manifest.json. Do not edit by hand.',
    '// Run `npm run gen-catalog` (dev, build and check run or verify it automatically).',
    "import type { CatalogEntry } from '@bulkhead/sdk';",
  ];
  plugins.forEach((p, i) => {
    lines.push(`import ${ident(i)} from '${rel(`${p.dir}/manifest.json`)}' with { type: 'json' };`);
    if (!p.code) lines.push(`import ${ident(i)}c from '${rel(`${p.dir}/content.json`)}' with { type: 'json' };`);
  });
  lines.push('', '/** Every plugin found on disk, sorted by folder. Manifests are static; code loads lazily. */');
  lines.push('export const catalog: CatalogEntry[] = [');
  plugins.forEach((p, i) => {
    lines.push(p.code
      ? `  { manifest: ${ident(i)}, load: () => import('${rel(`${p.dir}/index.ts`)}') }, // ${p.id}`
      : `  { manifest: ${ident(i)}, content: ${ident(i)}c }, // ${p.id}`);
  });
  lines.push('];', '');
  return lines.join('\n');
}

export function generate({ check = false } = {}) {
  const text = renderCatalog(discoverPlugins());
  const out = resolve(root, OUT);
  const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (current === text) return { changed: false };
  if (check) return { changed: true, stale: true };
  writeFileSync(out, text);
  return { changed: true };
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(root, 'scripts/gen-catalog.mjs')) {
  const check = process.argv.includes('--check');
  try {
    const r = generate({ check });
    if (r.stale) { console.error(`${OUT} is stale. Run "npm run gen-catalog".`); process.exit(1); }
    if (!check) console.log(r.changed ? `Wrote ${OUT}` : `${OUT} is up to date`);
  } catch (e) {
    console.error(`gen-catalog: ${e.message}`);
    process.exit(1);
  }
}
