#!/usr/bin/env python3
"""Import cropped 192px weapon-card previews from the original Gloamforge renders.

Usage: python3 scripts/import-weapon-previews.py [--check]
The previews are presentation-only. Runtime first-person views use the encoded painters generated by
scripts/weapon-painters.py; neither path replaces the editable Blender/GLB delivery assets.
"""
import hashlib
import io
import json
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / 'scripts/weapon-previews.json'
PROVENANCE = ROOT / 'public/weapons/provenance.json'


def digest(data):
    return hashlib.sha256(data).hexdigest()


def main(args):
    if args not in ([], ['--check']):
        raise ValueError(__doc__)
    config_bytes = CONFIG.read_bytes()
    config = json.loads(config_bytes)
    source_root = ROOT / config['source']
    size = config['size']
    margin = config['margin']
    if not isinstance(size, int) or size < 32 or size > 512:
        raise ValueError('invalid preview size')
    if not isinstance(margin, (int, float)) or margin < 0 or margin > 0.5:
        raise ValueError('invalid preview margin')
    ids = [w['id'] for w in config['weapons']]
    stems = [w['stem'] for w in config['weapons']]
    if len(ids) != len(set(ids)) or len(stems) != len(set(stems)):
        raise ValueError('duplicate weapon id or stem')

    records = []
    previews = []
    for weapon in config['weapons']:
        source = source_root / (weapon['stem'] + '.png')
        data = source.read_bytes()
        if digest(data) != weapon['sourceSha256']:
            raise ValueError('source hash mismatch: ' + str(source))
        with Image.open(io.BytesIO(data)) as image:
            if image.format != 'PNG' or image.mode != 'RGBA' or image.size != (512, 512):
                raise ValueError('expected a 512x512 RGBA PNG: ' + str(source))
            alpha = image.getchannel('A')
            bounds = alpha.point(lambda value: 255 if value > 8 else 0).getbbox()
            if bounds is None:
                raise ValueError('no visible pixels: ' + str(source))
            left, top, right, bottom = bounds
            side = round(max(right - left, bottom - top) * (1 + margin * 2))
            cx = (left + right) // 2
            cy = (top + bottom) // 2
            box = (cx - side // 2, cy - side // 2)
            canvas = Image.new('RGBA', (side, side), (0, 0, 0, 0))
            canvas.paste(image.crop((box[0], box[1], box[0] + side, box[1] + side)), (0, 0))
            preview = canvas.resize((size, size), Image.Resampling.LANCZOS)
            buffer = io.BytesIO()
            preview.save(buffer, format='PNG', optimize=True)
        output = buffer.getvalue()
        target = 'weapons/fantasy/' + weapon['stem'] + '.png'
        records.append({
            'id': weapon['id'], 'stem': weapon['stem'],
            'source': config['source'] + '/' + weapon['stem'] + '.png',
            'sourceSha256': weapon['sourceSha256'],
            'output': target, 'outputSha256': digest(output), 'size': [size, size],
        })
        previews.append((ROOT / 'public' / target, output))

    if args == ['--check']:
        provenance = json.loads(PROVENANCE.read_text())
        if provenance.get('configSha256') != digest(config_bytes):
            raise ValueError('configuration changed; reimport weapon previews')
        if provenance.get('assets') != records:
            raise ValueError('provenance records changed; reimport weapon previews')
        for path, expected in previews:
            if not path.is_file() or digest(path.read_bytes()) != digest(expected):
                raise ValueError('preview changed or missing: ' + str(path))
        print('Weapon previews verified:', len(previews))
        return

    for path, data in previews:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    PROVENANCE.parent.mkdir(parents=True, exist_ok=True)
    PROVENANCE.write_text(json.dumps({
        'configSha256': digest(config_bytes), 'source': config['source'],
        'license': config['license'],
        'processing': 'alpha-bounds crop, square transparent padding, %dpx Lanczos resize' % size,
        'assets': records,
    }, indent=2) + '\n')
    print('Imported', len(previews), 'weapon previews')


if __name__ == '__main__':
    try:
        main(sys.argv[1:])
    except (OSError, ValueError, KeyError, json.JSONDecodeError) as exc:
        print('weapon-previews:', exc, file=sys.stderr)
        sys.exit(1)
