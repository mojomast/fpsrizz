#!/usr/bin/env python3
"""Generate a synchronous TypeScript painter map from PNG renders.

Example: python3 scripts/weapon-painters.py --output src/plugins/my-theme/weapons.ts \
    --sprite weapon-pistol=assets/weapons/generic/pistol.png

Requires Pillow. Each --sprite maps a theme texture key to a PNG. Output is
created only after all inputs validate; use --force to replace an existing file.
Transparent pixels are canonicalized to transparent black. Visible RGBA bytes
and image dimensions are preserved. The input PNG hashes are embedded in output.
"""
import argparse
import base64
import hashlib
import io
import json
import os
from pathlib import Path
import re
import sys

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
MAX_PIXELS = 4096 * 4096


def encode(pixels):
    """16-bit LE runs: high bit means transparent, otherwise literal RGBA."""
    result = bytearray()
    count = len(pixels) // 4
    i = 0
    while i < count:
        transparent = pixels[i * 4 + 3] == 0
        end = i + 1
        while end < count and end - i < 32767 and (pixels[end * 4 + 3] == 0) == transparent:
            end += 1
        result.extend(((end - i) | (0x8000 if transparent else 0)).to_bytes(2, 'little'))
        if not transparent:
            result.extend(pixels[i * 4:end * 4])
        i = end
    return base64.b64encode(result).decode('ascii')


def generate(sprites, output):
    sdk = os.path.relpath(ROOT / 'src/sdk/index.ts', output.parent.resolve()).replace(os.sep, '/')
    if not sdk.startswith('.'):
        sdk = './' + sdk
    lines = [
        '// Generated by scripts/weapon-painters.py; do not edit.',
        f'import type {{ Painter }} from {json.dumps(sdk)};',
        '',
        'function painter(width: number, height: number, encoded: string): Painter {',
        '  return { width, height, paint(ctx) {',
        '    const data = atob(encoded);',
        '    const pixels = new Uint8ClampedArray(width * height * 4);',
        '    let src = 0, dst = 0;',
        '    while (src < data.length) {',
        '      const run = data.charCodeAt(src++) | (data.charCodeAt(src++) << 8);',
        '      const length = (run & 0x7fff) * 4;',
        '      if (run & 0x8000) dst += length;',
        '      else for (let end = dst + length; dst < end; dst++) pixels[dst] = data.charCodeAt(src++);',
        '    }',
        '    ctx.putImageData(new ImageData(pixels, width, height), 0, 0);',
        '  } };',
        '}',
        '',
        'export const weaponTextures: Record<string, Painter> = {',
    ]
    for key, width, height, encoded, digest in sorted(sprites):
        lines.append(f'  // PNG SHA-256: {digest}')
        lines.append(f'  {json.dumps(key)}: painter({width}, {height}, {json.dumps(encoded)}),')
    return '\n'.join(lines + ['};', ''])


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--output', required=True, type=Path, help='TypeScript output file; parent directory must exist')
    parser.add_argument('--sprite', required=True, action='append', metavar='KEY=PNG', help='theme texture key and PNG path; repeat for multiple sprites')
    parser.add_argument('--force', action='store_true', help='replace an existing output file')
    args = parser.parse_args(argv)
    output = args.output
    if output.suffix != '.ts' or not output.parent.is_dir():
        raise ValueError('output must be a .ts file in an existing directory')
    if output.exists() and not args.force:
        raise ValueError('output exists; pass --force to replace it')
    if output.is_symlink():
        raise ValueError('output must not be a symlink')
    sprites = []
    seen = set()
    for entry in args.sprite:
        key, sep, filename = entry.partition('=')
        if not sep or not filename or not re.fullmatch(r'[a-z0-9]+(?:[-/][a-z0-9]+)*', key):
            raise ValueError('sprite must be KEY=PNG with a lowercase theme key')
        if key in seen:
            raise ValueError(f'duplicate sprite key: {key}')
        seen.add(key)
        source = Path(filename)
        if source.resolve() == output.resolve() or (output.exists() and os.path.samefile(source, output)):
            raise ValueError('output must differ from every input')
        data = source.read_bytes()
        with Image.open(io.BytesIO(data)) as image:
            if image.format != 'PNG' or getattr(image, 'n_frames', 1) != 1:
                raise ValueError(f'{source}: expected a single-frame PNG')
            width, height = image.size
            if width < 1 or height < 1 or width * height > MAX_PIXELS:
                raise ValueError(f'{source}: invalid dimensions or exceeds {MAX_PIXELS} pixels')
            image.load()
            pixels = image.convert('RGBA').tobytes()
        sprites.append((key, width, height, encode(pixels), hashlib.sha256(data).hexdigest()))
    result = generate(sprites, output)
    # Exclusive creation avoids accidentally replacing a file created during validation.
    with output.open('w' if args.force else 'x', encoding='utf-8', newline='\n') as target:
        target.write(result)
    print(f'Generated {len(sprites)} painter(s) in {output}')


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, Image.DecompressionBombError) as exc:
        print(f'weapon-painters: {exc}', file=sys.stderr)
        sys.exit(1)
